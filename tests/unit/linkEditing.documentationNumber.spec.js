import linkEditing from '@/mixins/linkEditing';

describe('linkEditing documentation numbering', () => {
  afterEach(() => {
    delete window.ProcessMaker;
  });

  it('uses the numbering map generated by the documentation API', () => {
    window.ProcessMaker = {
      modeler: {
        documentationNumbers: {
          task_1: 4,
        },
      },
    };

    expect(linkEditing.methods.getNodeNumber.call({}, 'task_1')).toBe(4);
  });

  it('falls back to the XML order when no numbering map exists', () => {
    window.ProcessMaker = {
      $modeler: {
        currentXML: '<bpmn:task id="task_1"/><bpmn:endEvent id="end_1"/>',
      },
    };

    expect(linkEditing.methods.getNodeNumber.call({}, 'end_1')).toBe(2);
  });
});
